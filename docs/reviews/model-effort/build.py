"""Bundle the review into one HTML file that can be opened without a server."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
html = (ROOT / "index.template.html").read_text()
for marker, filename in (
    ("/* REVIEW_CSS */", "review.css"),
    ("/* APP_CSS */", "app.css"),
    ("/* REVIEW_JS */", "review.js"),
):
    assert html.count(marker) == 1, marker
    html = html.replace(marker, (ROOT / filename).read_text())
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build.py. -->", 1)
(ROOT / "index.html").write_text(html)
