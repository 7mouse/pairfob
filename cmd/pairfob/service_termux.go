const termuxServiceName = "pairfob"

// termuxRunScript is the runit service definition. The service directory is
// watched by termux-services' runsvdir, which replaces systemd/launchd here.
func termuxRunScript(layout serviceLayout) string {
	var b strings.Builder
	b.WriteString("#!" + filepath.Join(termuxPrefix(), "bin", "sh") + "\n")
	b.WriteString("# Generated by pairfob service install. Runit runs this file.\n")
	b.WriteString("# pairfob-exec: " + strconv.Quote(layout.ExecPath) + "\n")
	b.WriteString("exec 2>&1\n")
	b.WriteString("export HOME=" + shellQuote(layout.Home) + "\n")
	b.WriteString("export PATH=" + shellQuote(userServicePATH(layout.Home)) + "\n")
	for _, env := range serviceRuntimeEnvironment() {
		b.WriteString("export " + env[0] + "=" + shellQuote(env[1]) + "\n")
	}
	b.WriteString("exec " + shellQuote(layout.ExecPath) + " >>" + shellQuote(layout.LogPath) + " 2>&1\n")
	return b.String()
}

func termuxPrefix() string {
	if prefix := termux.Prefix(); prefix != "" {
		return prefix
	}
	return "/data/data/com.termux/files/usr"
}

// termuxConfiguredExecutable reads the path service install recorded. A run
// script without the marker was written by hand, so it cannot be verified.
func termuxConfiguredExecutable(layout serviceLayout) (string, error) {
	body, err := readServiceUnit(layout.UnitPath)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(body), "\n") {
		value, ok := strings.CutPrefix(line, "# pairfob-exec: ")
		if !ok {
			continue
		}
		path, err := strconv.Unquote(strings.TrimSpace(value))
		if err != nil || !filepath.IsAbs(path) {
			return "", errors.New("invalid service executable; run pairfob service install")
		}
		return path, nil
	}
	return "", errors.New("run script has no pairfob executable; run pairfob service install")
}

var termuxStatusLine = regexp.MustCompile(`^(run|down|fail|finish|start|stop): [^:]+: (.*)$`)
var termuxStatusPID = regexp.MustCompile(`^\(pid (\d+)\)`)

// parseTermuxObservation reads `sv status` output:
//
//	run: pairfob: (pid 1234) 12s
//	down: pairfob: 1s, normally up
func parseTermuxObservation(out string) (serviceObservation, error) {
	for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
		line = strings.TrimSpace(line)
		match := termuxStatusLine.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		pid := 0
		if pidMatch := termuxStatusPID.FindStringSubmatch(match[2]); pidMatch != nil {
			pid, _ = strconv.Atoi(pidMatch[1])
		}
		state := "stopped"
		detail := strings.TrimSpace(match[2])
		if match[1] == "run" {
			if pid > 0 {
				state = "running"
				if _, uptime, ok := strings.Cut(detail, ") "); ok {
					detail = fmt.Sprintf("pid %d, %s", pid, strings.TrimSpace(uptime))
				}
			} else {
				state = "starting"
			}
		}
		return serviceObservation{PID: pid, State: state, Detail: detail}, nil
	}
	return serviceObservation{}, fmt.Errorf("unexpected service status %q", strings.TrimSpace(out))
}

// waitForTermuxSupervise waits until runsvdir has picked up the new service
// directory. `sv` needs supervise/ok, which runsv creates after noticing it.
func waitForTermuxSupervise(layout serviceLayout, timeout time.Duration) error {
	supervise := filepath.Join(filepath.Dir(layout.UnitPath), "supervise")
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		if _, err := os.Stat(supervise); err == nil {
			return nil
		}
		time.Sleep(100 * time.Millisecond)
	}
	return fmt.Errorf("runit has not picked up %s; install termux-services (pkg install termux-services) and start a new Termux session", filepath.Dir(layout.UnitPath))
}

// termuxUnitRuntime compares the environment a previous run script carried, so
// a reinstall reports changed settings just like the systemd and launchd paths.
func termuxUnitRuntime(body []byte) (unitRuntime, error) {
	lines := strings.Split(string(body), "\n")
	if !strings.Contains(string(body), "# pairfob-exec: ") {
		return unitRuntime{}, errors.New("not a pairfob run script")
	}
	env := map[string]string{}
	for _, line := range lines {
		rest, ok := strings.CutPrefix(line, "export ")
		if !ok {
			continue
		}
		name, value, ok := strings.Cut(rest, "=")
		if !ok || !environmentName.MatchString(name) || len(value) < 2 || value[0] != '\'' || value[len(value)-1] != '\'' {
			return unitRuntime{}, errors.New("not a generated run script")
		}
		env[name] = strings.ReplaceAll(value[1:len(value)-1], `'\''`, "'")
	}
	return unitRuntime{env: env}, nil
}

func termuxRequireRunit() error {
	if _, err := exec.LookPath("sv"); err != nil {
		return errors.New("runit is not installed; run: pkg install termux-services")
	}
	return nil
}

func observeTermuxService(layout serviceLayout) (serviceObservation, error) {
	out, err := runServiceCommand([]string{"sv", "status", termuxServiceName})
	observation, parseErr := parseTermuxObservation(string(out))
	if parseErr != nil {
		return serviceObservation{}, fmt.Errorf("read user service: %w: %s", err, strings.TrimSpace(string(out)))
	}
	exe, exeErr := termuxConfiguredExecutable(layout)
	if exeErr != nil {
		return serviceObservation{}, exeErr
	}
	observation.Executable = exe
	return observation, nil
}
